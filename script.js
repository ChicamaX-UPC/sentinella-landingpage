  /** Una sola imagen de hero (dashboard en monitor). */
  const HERO_IMG = "assets/hero-dashboard.jpeg";

  function getPreferredLang() {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "es") return saved;
    const nav = navigator.language || "en";
    return nav.toLowerCase().startsWith("es") ? "es" : "en";
  }

  function applyTranslations(lang) {
    const dict = T[lang];
    if (!dict) return;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key || dict[key] === undefined) return;
      el.textContent = dict[key];
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (!key || dict[key] === undefined) return;
      if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement) {
        el.placeholder = dict[key];
      }
    });

    document.querySelectorAll("[data-lang-visible]").forEach((el) => {
      const want = el.getAttribute("data-lang-visible");
      if (want === "en" || want === "es") el.hidden = want !== lang;
    });

    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && dict["meta.description"]) metaDesc.setAttribute("content", dict["meta.description"]);

    const heroImg = document.getElementById("heroDashboardImg");
    if (heroImg instanceof HTMLImageElement) {
      heroImg.src = HERO_IMG;
      if (dict["hero.imgAlt"]) heroImg.alt = dict["hero.imgAlt"];
    }

    const footerCopy = document.getElementById("footerCopy");
    if (footerCopy && dict["footer.copy"]) {
      footerCopy.textContent = dict["footer.copy"].replace("{year}", String(new Date().getFullYear()));
    }

    document.documentElement.lang = lang === "es" ? "es" : "en";
    localStorage.setItem(STORAGE_KEY, lang);

    document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
      const bLang = btn.getAttribute("data-lang-btn");
      btn.setAttribute("aria-pressed", bLang === lang ? "true" : "false");
      btn.classList.toggle("is-active", bLang === lang);
    });
  }

  document.documentElement.classList.add("js");

  const initialLang = getPreferredLang();
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyTranslations(initialLang));
  } else {
    applyTranslations(initialLang);
  }

  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.getAttribute("data-lang-btn");
      if (lang === "en" || lang === "es") applyTranslations(lang);
    });
  });

  const toggle = document.getElementById("navToggle");
  const nav = document.getElementById("mainNav");
  const navLinks = nav ? nav.querySelectorAll('a[href^="#"]') : [];

  function setNav(open) {
    if (!toggle || !nav) return;
    nav.classList.toggle("is-open", open);
    toggle.setAttribute("aria-expanded", open ? "true" : "false");
    const lang = document.documentElement.lang === "es" ? "es" : "en";
    const k = open ? "toggle.close" : "toggle.open";
    if (T[lang] && T[lang][k]) toggle.setAttribute("aria-label", T[lang][k]);
    document.body.style.overflow = open ? "hidden" : "";
  }

  if (toggle && nav) {
    toggle.addEventListener("click", () => setNav(!nav.classList.contains("is-open")));
    navLinks.forEach((a) =>
      a.addEventListener("click", () => {
        if (window.matchMedia("(max-width: 900px)").matches) setNav(false);
      }),
    );
    window.addEventListener(
      "resize",
      debounce(() => {
        if (window.innerWidth > 900) setNav(false);
      }, 160),
    );
  }

  const form = document.getElementById("contactForm");
  const fb = document.getElementById("formFeedback");
  if (form && fb) {
    form.addEventListener("submit", (ev) => {
      ev.preventDefault();
      fb.hidden = false;
      const org = (form.elements.company?.value ?? "").trim();
      const name = (form.elements.name?.value ?? "").trim();
      const email = (form.elements.email?.value ?? "").trim();
      const msg = (form.elements.msg?.value ?? "").trim();
      const valid = email.includes("@") && org.length >= 2 && msg.length >= 12;
      const lang = document.documentElement.lang === "es" ? "es" : "en";
      if (!valid) {
        fb.dataset.state = "warn";
        fb.textContent = T[lang]["contact.feedbackWarn"];
        return;
      }
      const to = "contacto@chicamax.com";
      const subject = encodeURIComponent(`Demo Sentinella — ${org}`);
      const body = encodeURIComponent(
        `${msg}\n\n---\nNombre: ${name}\nEmpresa: ${org}\nCorreo: ${email}\n(landing Sentinella / ChicamaX)`,
      );
      fb.dataset.state = "ok";
      fb.textContent = T[lang]["contact.feedbackOk"];
      window.location.href = `mailto:${to}?subject=${subject}&body=${body}`;
      form.reset();
    });
  }
